"""
Executive status report and SteerCo talking points, generated from structured
data only. Every bullet ends with a [source] tag. Output is marked DRAFT until
a named reviewer releases it in the app.
"""
from __future__ import annotations

import pandas as pd

from . import analysis
from .loader import ProgramData

RAG_ICON = {"Green": "G", "Amber": "A", "Red": "R"}


def _d(ts) -> str:
    return pd.Timestamp(ts).strftime("%d %b")


def executive_report(pd_: ProgramData, accepted_candidates: list[dict] | None = None,
                     reviewer: str = "", released: bool = False) -> str:
    ms_sum = analysis.milestone_summary(pd_)
    mflags = analysis.milestone_flags(pd_)
    rflags = analysis.raid_flags(pd_)
    crit, dims = analysis.readiness_scorecard(pd_)
    gng = analysis.go_no_go(dims)
    risks = analysis.top_risks(pd_, 5)
    accepted_candidates = accepted_candidates or []

    status = "RELEASED" if released and reviewer else "DRAFT, not for distribution"
    lines = []
    lines.append(f"# {pd_.meta.get('program', 'Program')} | {pd_.meta.get('release', '')} | Executive status")
    lines.append(f"As of {pd_.as_of.date()} | Cut-over {pd_.meta.get('cutover_weekend', '')} | "
                 f"Go/no-go SteerCo {pd_.meta.get('go_no_go_steerco', '')} | Status: **{status}**"
                 + (f" | Reviewer: {reviewer}" if reviewer else ""))
    lines.append("")

    # Headline
    lines.append("## Headline")
    lines.append(f"- Readiness recommendation: **{gng['recommendation']}**. Rule applied: {gng['rule']}. [source: {gng['source']}]")
    worst = dims.sort_values("rag", key=lambda s: s.map(analysis.RAG_ORDER)).iloc[0]
    lines.append(f"- Weakest dimension: {worst.dimension_id} {worst.dimension} ({worst.rag}). "
                 f"[source: readiness_kpis.csv, {worst.dimension_id}]")
    lines.append(f"- Milestones: {ms_sum['complete']} of {ms_sum['total']} complete, {ms_sum['slipping']} slipping, "
                 f"{ms_sum['delayed']} marked delayed. [source: milestone_plan.xlsx]")
    lines.append("")

    # Scorecard
    lines.append("## Readiness scorecard")
    lines.append("| Dimension | RAG | Red / Amber / Green criteria | Weakest criterion |")
    lines.append("|---|---|---|---|")
    for d in dims.itertuples():
        c = crit[crit.dimension_id == d.dimension_id]
        weakest = c.sort_values("rag", key=lambda s: s.map(analysis.RAG_ORDER)).iloc[0]
        lines.append(f"| {d.dimension_id} {d.dimension} | {d.rag} | {d.red} / {d.amber} / {d.green} | "
                     f"{weakest.criterion}: {weakest.display} [source: {weakest.source}] |")
    lines.append("")

    # Slips and conflicts
    lines.append("## Schedule: slips and dependency conflicts")
    hi = mflags[mflags.flag.isin(["Slip", "Overdue", "Dependency conflict"])].sort_values(["severity", "flag"])
    if hi.empty:
        lines.append("- None.")
    for f in hi.itertuples():
        lines.append(f"- {f.flag} ({f.severity}): {f.milestone_id} {f.milestone}, owner {f.owner or 'none'}. {f.detail}. [source: {f.source}]")
    lines.append("")

    # Risks
    lines.append("## Top risks and issues")
    for r in risks.itertuples():
        due = _d(r.due_date) if pd.notna(r.due_date) else "no date"
        lines.append(f"- {r.id} ({r.type}, {r.severity}{'/' + r.likelihood if r.likelihood else ''}, due {due}): {r.title}. "
                     f"Owner: {r.owner or 'UNASSIGNED'}. Mitigation: {r.mitigation or 'none recorded'} [source: {r.source}]")
    hyg = rflags[rflags.flag.isin(["Unowned", "Past due"])]
    if not hyg.empty:
        lines.append("")
        lines.append("RAID hygiene:")
        for h in hyg.itertuples():
            lines.append(f"- {h.flag}: {h.raid_id} {h.title}. {h.detail}. [source: {h.source}]")
    lines.append("")

    # New items from weekly updates (reviewed only)
    lines.append("## New items from weekly updates (reviewer-accepted only)")
    if not accepted_candidates:
        lines.append("- No accepted items. Review proposals in the 'Weekly updates' tab.")
    for c in accepted_candidates:
        lines.append(f"- [{c['type'].upper()}, {c['severity']}] {c['workstream']}: \"{c['sentence']}\" [source: {c['file']}]")
    lines.append("")

    # Decisions
    lines.append("## Decisions requested from the SteerCo")
    decisions = [c for c in accepted_candidates if c["type"] == "decision"]
    if gng["red"]:
        lines.append(f"- Approve mitigation for red dimension(s) {', '.join(gng['red'])} or defer cut-over. [source: {gng['source']}]")
    for c in decisions:
        lines.append(f"- {c['workstream']}: \"{c['sentence']}\" [source: {c['file']}]")
    if not decisions and not gng["red"]:
        lines.append("- None recorded.")
    lines.append("")
    lines.append("---")
    lines.append("Generated by the Transformation Cockpit from structured program data. Synthetic data; no client information. "
                 "Every bullet carries a source reference. A named reviewer must release this report before distribution.")
    return "\n".join(lines)


def steerco_talking_points(pd_: ProgramData, accepted_candidates: list[dict] | None = None) -> str:
    crit, dims = analysis.readiness_scorecard(pd_)
    gng = analysis.go_no_go(dims)
    risks = analysis.top_risks(pd_, 3)
    mflags = analysis.milestone_flags(pd_)
    conflicts = mflags[mflags.flag == "Dependency conflict"]
    accepted_candidates = accepted_candidates or []
    decisions = [c for c in accepted_candidates if c["type"] == "decision"]

    pts = ["# SteerCo talking points (draft)", ""]
    pts.append("**1. Where we stand**")
    pts.append(f"- Recommendation today is *{gng['recommendation']}*. {gng['rule']}. [source: {gng['source']}]")
    for d in dims[dims.rag != "Green"].itertuples():
        c = crit[(crit.dimension_id == d.dimension_id) & (crit.rag != "Green")]
        items = "; ".join(f"{r.criterion} at {r.display}" for r in c.itertuples())
        pts.append(f"- {d.dimension_id} {d.dimension} is {d.rag}: {items}. [source: readiness_kpis.csv]")
    pts.append("")
    pts.append("**2. What is on the critical path**")
    for f in conflicts.itertuples():
        pts.append(f"- {f.milestone_id} {f.milestone}: {f.detail}. [source: {f.source}]")
    if conflicts.empty:
        pts.append("- No dependency conflicts in the plan.")
    pts.append("")
    pts.append("**3. The three risks that matter most**")
    for r in risks.itertuples():
        pts.append(f"- {r.id} {r.title}. Mitigation: {r.mitigation}. [source: {r.source}]")
    pts.append("")
    pts.append("**4. What we need from the committee**")
    if gng["red"]:
        pts.append(f"- A decision on the mitigation for {', '.join(gng['red'])}, which is the only red dimension. [source: {gng['source']}]")
    for c in decisions:
        pts.append(f"- {c['workstream']}: \"{c['sentence']}\" [source: {c['file']}]")
    if not decisions:
        pts.append("- Accept decision-type proposals in the 'Weekly updates' tab to list them here.")
    pts.append("")
    pts.append("**5. Next checkpoint**")
    pts.append(f"- Go/no-go SteerCo on {pd_.meta.get('go_no_go_steerco', '')}; final confirmation at T-3 days. [source: 01_Readiness_Framework.md section 5]")
    return "\n".join(pts)
