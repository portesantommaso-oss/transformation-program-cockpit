"""
Writes the sample executive status report (Markdown and PDF) from the
synthetic data, with the decision-type proposals pre-accepted so the
'Decisions requested' section is populated.

    python cockpit/make_sample_report.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "cockpit"))

from engine import report  # noqa: E402
from engine.extractor import extract_all  # noqa: E402
from engine.loader import load_program  # noqa: E402


def md_to_pdf(md: str, out: Path) -> None:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Heading1"], fontSize=13, spaceAfter=2, textColor=colors.HexColor("#36454F"))
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=10.5, spaceBefore=6, spaceAfter=2, textColor=colors.HexColor("#36454F"))
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=8, leading=10)
    bullet = ParagraphStyle("bl", parent=body, leftIndent=8, bulletIndent=0)
    small = ParagraphStyle("s", parent=body, fontSize=7, leading=9, textColor=colors.HexColor("#7A8C99"))

    def esc(t: str) -> str:
        t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
        t = re.sub(r"\[source: (.+?)\]", r"<font color='#7A8C99' size='6.5'>[\1]</font>", t)
        return t

    flow = []
    lines = md.splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("# "):
            flow.append(Paragraph(esc(ln[2:]), h1))
        elif ln.startswith("## "):
            flow.append(Paragraph(esc(ln[3:]), h2))
        elif ln.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip("|").split("|")]
                if not all(set(c) <= set("-: ") for c in cells):
                    rows.append([Paragraph(esc(c), body) for c in cells])
                i += 1
            t = Table(rows, colWidths=[52 * mm, 16 * mm, 32 * mm, 80 * mm], repeatRows=1)
            t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F2F2F2")),
                                   ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#B0BEC5")),
                                   ("VALIGN", (0, 0), (-1, -1), "TOP"),
                                   ("FONTSIZE", (0, 0), (-1, -1), 7.5)]))
            flow.append(t)
            continue
        elif ln.startswith("- "):
            flow.append(Paragraph(esc(ln[2:]), bullet, bulletText="•"))
        elif ln.strip() == "---":
            flow.append(Spacer(1, 4))
        elif ln.strip():
            flow.append(Paragraph(esc(ln), small if ln.startswith("Generated by") else body))
        else:
            flow.append(Spacer(1, 2))
        i += 1

    doc = SimpleDocTemplate(str(out), pagesize=A4, leftMargin=14 * mm, rightMargin=14 * mm,
                            topMargin=12 * mm, bottomMargin=12 * mm, title="Executive status report (sample)")
    doc.build(flow)


def main() -> None:
    prog = load_program(ROOT / "data")
    cands = extract_all(prog.updates, engine="rules")
    accepted = [c.to_dict() for c in cands if c.type == "decision"]
    md = report.executive_report(prog, accepted, reviewer="PMO Lead (sample)", released=False)
    (ROOT / "04_Sample_Executive_Status_Report.md").write_text(md, encoding="utf-8")
    md_to_pdf(md, ROOT / "04_Sample_Executive_Status_Report.pdf")
    tp = report.steerco_talking_points(prog, accepted)
    (ROOT / "05_Sample_SteerCo_Talking_Points.md").write_text(tp, encoding="utf-8")
    print("written 04_Sample_Executive_Status_Report.md/.pdf and 05_Sample_SteerCo_Talking_Points.md")


if __name__ == "__main__":
    main()
